"""Case spec -> runnable target. A "case" is what a user enters in the /new wizard:

{
  "id": "primes-fast",                      # [a-z0-9-]
  "name": "Make count_primes fast",
  "goal": "Make count_primes as fast as possible while returning the same answer.",
  "workspace": {"path": "/abs/path/to/code"},          # on the worker machine
  "editable": ["primes.py"],
  "measure": {"command": "python3 bench.py", "parse": {"mode": "json_key", "key": "seconds"}, "timeout_s": 120},
  "metric": {"label": "seconds", "unit": "s", "direction": "lower"},
  "verify": {"mode": "json_flag", "key": "correct"},   # or test_command / same_output / none (see adapter.py)
  "budget": {"max_experiments": 10, "backend": "anthropic", "model": "sonnet", "budget_usd": 5}
}

build_target(spec) writes cases/<id>/target/ (target.json, program.md, case.json, links to the workspace) so the
existing runner, hooks, gate and UI work unchanged. dry_run(spec) evaluates the untouched workspace once.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
import tempfile
from pathlib import Path
from typing import Any

from .adapter import evaluate
from .events import ROOT

CASES = ROOT / "cases"
ADAPTER = ROOT / "glassbox" / "adapter.py"
SKIP = {".git", "node_modules", ".venv", "venv", "__pycache__", ".next", ".DS_Store"}
RESERVED = {"program.md", "target.json", "case.json"}  # generated by Glassbox
ID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,47}$")

VERIFY_TEXT = {
    "json_flag": "The evaluator checks that the measure output reports `{key}: true`; otherwise the run counts as incorrect.",
    "test_command": "The evaluator runs `{command}` for you after measuring; it must pass (exit 0) or the run counts as incorrect. You don't need to run it yourself.",
    "same_output": "The evaluator runs `{command}` for you; its output must match what it printed before your changes, or the run counts as incorrect.",
    "none": "There is no automatic correctness check. Do not trade correctness for the metric; say so in record_result if unsure.",
}


def validate(spec: dict[str, Any]) -> list[str]:
    errs = []
    if not ID_RE.match(str(spec.get("id", ""))):
        errs.append("id must be 2-48 chars of a-z, 0-9 and dashes")
    for k in ("name", "goal"):
        if not str(spec.get(k, "")).strip():
            errs.append(f"{k} is required")
    ws = Path(str((spec.get("workspace") or {}).get("path", "")))
    if not ws.is_absolute() or not ws.is_dir():
        errs.append(f"workspace.path must be an existing absolute directory on the worker ({ws})")
    if not spec.get("editable"):
        errs.append("editable: list at least one file or glob the agent may change")
    m = spec.get("measure") or {}
    if not str(m.get("command", "")).strip():
        errs.append("measure.command is required")
    if (m.get("parse") or {}).get("mode", "last_number") not in ("json_key", "regex", "last_number"):
        errs.append("measure.parse.mode must be json_key, regex or last_number")
    if (spec.get("metric") or {}).get("direction") not in ("lower", "higher"):
        errs.append("metric.direction must be lower or higher")
    ev = spec.get("evidence") or {}
    if ev and not isinstance(ev.get("commands", []), list):
        errs.append("evidence.commands must be a list of commands")
    if not isinstance(spec.get("hidden", []), list):
        errs.append("hidden must be a list of top-level files or folders")
    v = spec.get("verify") or {}
    if v.get("mode") not in VERIFY_TEXT:
        errs.append("verify.mode must be json_flag, test_command, same_output or none")
    if v.get("mode") in ("test_command", "same_output") and not str(v.get("command", "")).strip():
        errs.append("verify.command is required for this verification mode")
    return errs


def program_md(spec: dict[str, Any]) -> str:
    m, v = spec["metric"], spec["verify"]
    verify = VERIFY_TEXT[v["mode"]].format(key=v.get("key", "correct"), command=v.get("command", ""))
    better = "Lower is better." if m["direction"] == "lower" else "Higher is better."
    return f"""# {spec['name']}

{spec['goal']}

## The metric
- Run `{{EVAL_CMD}}` to measure. It prints one line with **{m['label']}**{f" ({m['unit']})" if m.get('unit') else ""}. {better}
- Baseline: {{BASELINE}}. The harness records every measurement; you never report numbers yourself.
- Correctness: {verify}

## What you may change
- Only: {', '.join(f'`{g}`' for g in spec['editable'])}. Other edits are blocked. You cannot modify the evaluator.

## The loop (Glassbox rules, required)
1. Call `get_beliefs` at the start and whenever you're unsure what to try next.
2. Before every measurement, call `propose_hypothesis`: a specific claim, its topic, your reason, the predicted
   direction of {m['label']} (`decrease` / `increase` / `no_change`), confidence 0-1, and the file + region you
   will change. Measurement is blocked until a hypothesis is armed.
3. Make the change, then run `{{EVAL_CMD}}`.
4. Call `record_result` with the hypothesis ids, whether you kept the change, and what you learned.
5. Keep with `git add -A && git commit -m "<id>: <what>"`, or revert with `git checkout -- .`.
6. If a new hypothesis builds on, refines or contradicts an earlier one, call `link_hypotheses`.
7. `close_hypothesis` when the evidence is clear. One idea per experiment.

## Budget
- {{MAX_EXPERIMENTS}} measurements. Use them all; make bold predictions; a refuted hypothesis is useful evidence.
- Work autonomously; keep messages short. After the last run, call `get_beliefs` and summarize what you learned.
"""


def build_target(spec: dict[str, Any]) -> Path:
    errs = validate(spec)
    if errs:
        raise ValueError("; ".join(errs))
    tdir = CASES / spec["id"] / "target"
    if tdir.exists():
        shutil.rmtree(tdir)
    tdir.mkdir(parents=True)
    ws = Path(spec["workspace"]["path"])
    # Names Glassbox generates are never linked (writing them must not touch the user's workspace).
    hidden = {h.strip("/") for h in spec.get("hidden", [])}
    entries = sorted(p.name for p in ws.iterdir() if p.name not in SKIP and p.name not in RESERVED and p.name not in hidden)
    for name in entries:  # the runner copies these into each run's fresh git workdir
        (tdir / name).symlink_to(ws / name)
    case_file = CASES / spec["id"] / "case.json"
    case_file.write_text(json.dumps(spec, indent=2))
    write_fresh(tdir / "program.md", program_md(spec))
    m = spec["metric"]
    target = {
        "name": spec["name"],
        "description": spec["goal"],
        "metric": {"key": "value", "label": m["label"], "short": m.get("short") or m["label"].split()[0],
                   "unit": m.get("unit", ""), "direction": m["direction"]},
        "breakdown": None,
        "editable": spec["editable"],
        "copy": [e for e in entries if e not in ("program.md",)],
        "program": "program.md",
        "verify": spec["verify"],
        "allow": [f"Bash({c}:*)" for c in (spec.get("evidence") or {}).get("commands", [])],
        "observe": {"match": [c.split()[-1] if c.split() else c for c in (spec.get("evidence") or {}).get("commands", [])]},
        "hidden": sorted(hidden),
        "eval": {
            "command": f"{{python}} {ADAPTER} --case {case_file} --workdir . --out ../result.json",
            "match": "adapter.py",
            "result_file": "result.json",
            "correct_key": "correct",
            "error_key": "error",
        },
    }
    write_fresh(tdir / "target.json", json.dumps(target, indent=2))
    return tdir


def write_fresh(path: Path, text: str) -> None:
    """Write a new regular file; never follow a symlink into the user's workspace."""
    if path.is_symlink() or path.exists():
        path.unlink()
    path.write_text(text)


def dry_run(spec: dict[str, Any]) -> dict[str, Any]:
    """Evaluate the untouched workspace once: proves the metric parses and verification passes."""
    errs = validate(spec)
    if errs:
        return {"ok": False, "errors": errs}
    with tempfile.TemporaryDirectory(prefix="glassbox-dry-") as tmp:
        run_dir = Path(tmp)
        work = run_dir / "work"
        hidden = [h.strip("/") for h in spec.get("hidden", [])]
        shutil.copytree(spec["workspace"]["path"], work, ignore=shutil.ignore_patterns(*SKIP, *hidden))
        r = evaluate(spec, work, run_dir / "result.json")
        if r["correct"] and spec["verify"]["mode"] == "same_output":  # second pass proves the check is stable
            r2 = evaluate(spec, work, run_dir / "result.json")
            if not r2["correct"]:
                r = {**r2, "error": {"kind": "unstable_output", "message": "verify output differs between two unchanged runs"}}
    return {"ok": bool(r["correct"]), "value": r["value"], "correct": r["correct"], "error": r["error"]}


if __name__ == "__main__":  # python -m glassbox.cases spec.json  -> dry run + build
    spec = json.loads(Path(sys.argv[1]).read_text())
    print(json.dumps(dry_run(spec), indent=2))
    print(build_target(spec))
